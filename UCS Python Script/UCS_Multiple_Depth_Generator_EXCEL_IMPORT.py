def generate_ucs(
    target_ucs,
    diameter_cm,
    height_cm,
    ring_constant,
    soil_type,
    seed,
):
    """Generate the 32 PR observations for one depth."""

    if soil_type not in SOIL_PROFILES:
        raise ValueError("Invalid soil type.")

    rng = random.Random(seed)
    profile = SOIL_PROFILES[soil_type]

    area0 = math.pi * diameter_cm * diameter_cm / 4.0

    # Exact strain values represented by the template.
    strain = [
        (dial / 1000.0) / height_cm * 100.0
        for dial in DIAL_DIVISIONS
    ]

    # Peak strain is selected according to the soil type.
    peak_target = rng.uniform(*profile["peak"])
    peak_index = min(
        range(len(strain)),
        key=lambda i: abs(strain[i] - peak_target)
    )

    # Keep enough points after peak to show post-peak behaviour.
    peak_index = max(4, min(peak_index, 25))

    strength_factor = max(
        0.975,
        min(1.025, rng.gauss(1.0, 0.010))
    )
    target_actual = target_ucs * strength_factor

    normalized = []

    for i in range(32):
        if i <= peak_index:
            x = i / peak_index

            # Initial seating/toe followed by nonlinear hardening.
            if x <= 0.12:
                y = profile["toe"] * (x / 0.12) ** 1.55
            else:
                z = (x - 0.12) / 0.88
                y = profile["toe"] + (
                    1.0 - profile["toe"]
                ) * (
                    0.28 * z + 0.72 * z ** 0.62
                )

            y *= 1.0 + rng.gauss(
                0.0, profile["noise"] * 0.35
            )

        else:
            q = (
                (i - peak_index)
                / (31 - peak_index)
            )

            residual = rng.uniform(
                *profile["residual"]
            )

            y = 1.0 - (
                1.0 - residual
            ) * q ** profile["drop"]

            y *= 1.0 + rng.gauss(
                0.0, profile["noise"]
            )

        normalized.append(max(0.0, y))

    normalized[peak_index] = 1.0

    # Convert desired stress to PR reading.
    pr = []

    for i in range(32):
        area = area0 / (
            1.0 - strain[i] / 100.0
        )

        desired_stress = (
            target_actual * normalized[i]
        )

        ideal_pr = (
            desired_stress * area
            / ring_constant
        )

        # Simulated logger/proving-ring variation.
        if i < 3:
            factor = rng.uniform(0.94, 0.985)
        else:
            factor = rng.uniform(0.985, 1.015)

        reading = max(
            0.0,
            ideal_pr * factor
        )

        pr.append(int(round(reading)))

    # Avoid implausible downward movement before failure.
    for i in range(1, peak_index + 1):
        if pr[i] < pr[i - 1]:
            pr[i] = pr[i - 1]

    # Calculate actual stress after integer PR rounding.
    stress = []

    for i in range(32):
        area = area0 / (
            1.0 - strain[i] / 100.0
        )
        stress.append(
            pr[i] * ring_constant / area
        )

    actual_ucs = max(stress)
    actual_peak = stress.index(actual_ucs)

    return {
        "dial": DIAL_DIVISIONS[:],
        "strain": strain,
        "pr": pr,
        "stress": stress,
        "peak_index": actual_peak,
        "actual_ucs": actual_ucs,
        "area0": area0,
    }


def populate_xlsm(
    template_path,
    output_path,
    specimen,
    result,
):
    """Copy template and populate the Trial_01 sheet."""

    if not OPENPYXL_OK:
        raise RuntimeError(
            "openpyxl is not installed.\n\n"
            "Run:\n"
            "py -m pip install openpyxl"
        )

    if not os.path.isfile(template_path):
        raise FileNotFoundError(
            "Selected XLSM template was not found."
        )

    shutil.copy2(template_path, output_path)

    wb = load_workbook(
        output_path,
        keep_vba=True
    )

    if "Trial_01" not in wb.sheetnames:
        wb.close()
        raise ValueError(
            "The selected template does not contain "
            "a sheet named 'Trial_01'."
        )

    ws = wb["Trial_01"]

    # ----------------------------------------------------------
    # Header
    # ----------------------------------------------------------
    ws["D1"] = specimen["bh_id"]
    ws["D2"] = specimen["depth"]
    ws["D3"] = specimen["diameter"]

    # User requested these cells to be calculated in Excel.
    ws["D4"] = "=(PI()/4)*D3^2"

    ws["D5"] = specimen["height"]
    ws["D6"] = specimen["density"]

    # Volume = Area x Height; density in gm/cc gives gm.
    ws["D7"] = "=D4*D5*D6"

    ws["D8"] = specimen["ring_constant"]

    # Keep assigned UCS available in H2, as in the basic macro.
    ws["H2"] = specimen["ucs"]

    # ----------------------------------------------------------
    # Observation table
    # ----------------------------------------------------------
    for i, row in enumerate(ROWS):

        # A: SR No.
        ws.cell(row, 1).value = i + 1

        # B: fixed dial reading
        ws.cell(row, 2).value = DIAL_DIVISIONS[i]

        # C: dial reading in cm
        ws.cell(row, 3).value = (
            f"=B{row}/1000"
        )

        # D: axial strain
        ws.cell(row, 4).value = (
            f"=(C{row}/$D$5)*100"
        )

        # E: average cross-sectional area
        ws.cell(row, 5).value = (
            f"=$D$4/(1-(D{row}/100))"
        )

        # F: generated PR reading
        ws.cell(row, 6).value = result["pr"][i]

        # G: axial load
        ws.cell(row, 7).value = (
            f"=F{row}*$D$8"
        )

        # H: compressive stress
        ws.cell(row, 8).value = (
            f"=G{row}/E{row}"
        )

    # Optional sample information only if matching cells/labels
    # already exist in the supplied template. We do NOT invent a
    # fixed destination because it was not specified by the user.
    #
    # The information remains in the GUI/project data and is shown
    # in the generated filename/status.

    try:
        wb.calculation.fullCalcOnLoad = True
        wb.calculation.forceFullCalc = True
        wb.calculation.calcMode = "auto"
    except Exception:
        pass

    wb.save(output_path)
    wb.close()


