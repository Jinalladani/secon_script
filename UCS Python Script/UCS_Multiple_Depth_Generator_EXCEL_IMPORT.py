"""
UCS MULTIPLE-DEPTH SYNTHETIC DATA GENERATOR
===========================================

Purpose
-------
Generate synthetic UCS proving-ring readings and populate the user's
existing XLSM template.

IMPORTANT TEMPLATE MAPPING
--------------------------
Header:
D1 = BH ID
D2 = Depth
D3 = Diameter of Specimen (cm)
D4 = Initial Area A0 (Excel formula from D3)
D5 = Initial Height (cm)
D6 = Density (gm/cc)
D7 = Sample Weight Taken (Excel formula from D4*D5*D6)
D8 = PR Constant (kg/div), default 0.325

Observation table:
A11:A42 = SR No. 1 to 32
B11:B42 = fixed dial reading 0,50,100,...,1550
C11:C42 = =B/1000
D11:D42 = =(C/$D$5)*100
E11:E42 = =$D$4/(1-(D/100))
F11:F42 = synthetic PR reading generated by Python
G11:G42 = =F*$D$8
H11:H42 = =G/E

No CSV export.

Multiple-depth requirement
--------------------------
Every depth has its own:
- Depth
- Diameter
- Height
- Density
- Assigned UCS
- PR Constant
- Random Seed
- Soil Type
- Sample Type

BH ID is common to the project.
"""

