    def import_excel_input(self):
        """Import multiple-depth input rows from an Excel .xlsx file."""
        if not OPENPYXL_OK:
            messagebox.showerror(
                "Excel Import Error",
                "openpyxl is not installed.\n\n"
                "Run:\npy -m pip install openpyxl"
            )
            return

        f = filedialog.askopenfilename(
            title="Select UCS Input Excel File",
            filetypes=[("Excel Workbook", "*.xlsx")]
        )
        if not f:
            return

        try:
            wb = load_workbook(f, data_only=True, read_only=True)
            ws = wb.active

            headers = [str(c.value).strip() if c.value is not None else ""
                       for c in ws[1]]

            required = [
                "Depth", "Diameter (cm)", "Height (cm)",
                "Density (gm/cc)", "Assigned UCS (kg/cm²)",
                "PR Constant (kg/div)", "Soil Type",
                "Sample Type", "Random Seed"
            ]

            # Accept a few natural header variants while keeping the
            # input template simple and explicit.
            aliases = {
                "Depth": ["Depth", "Depth (m)"],
                "Diameter (cm)": ["Diameter (cm)", "Diameter"],
                "Height (cm)": ["Height (cm)", "Height"],
                "Density (gm/cc)": ["Density (gm/cc)", "Density (g/cc)", "Density"],
                "Assigned UCS (kg/cm²)": [
                    "Assigned UCS (kg/cm²)", "Assigned UCS", "UCS"
                ],
                "PR Constant (kg/div)": [
                    "PR Constant (kg/div)", "PR Constant", "Ring Constant"
                ],
                "Soil Type": ["Soil Type", "Soil"],
                "Sample Type": ["Sample Type", "Sample"],
                "Random Seed": ["Random Seed", "Seed"],
            }

            index_map = {}
            for key, options in aliases.items():
                found = None
                for option in options:
                    if option in headers:
                        found = headers.index(option)
                        break
                if found is None:
                    raise ValueError(
                        f"Missing required column: {key}"
                    )
                index_map[key] = found

            # Optional BH ID column. If present, use it as the common BH ID.
            bh_idx = None
            for option in ("BH ID", "BH_ID", "Borehole ID"):
                if option in headers:
                    bh_idx = headers.index(option)
                    break

            rows = []
            for excel_row in ws.iter_rows(min_row=2, values_only=True):
                if not any(v is not None and str(v).strip() != "" for v in excel_row):
                    continue

                def val(key):
                    return excel_row[index_map[key]]

                row = [
                    "" if val("Depth") is None else val("Depth"),
                    "" if val("Diameter (cm)") is None else val("Diameter (cm)"),
                    "" if val("Height (cm)") is None else val("Height (cm)"),
                    "" if val("Density (gm/cc)") is None else val("Density (gm/cc)"),
                    "" if val("Assigned UCS (kg/cm²)") is None else val("Assigned UCS (kg/cm²)"),
                    "" if val("PR Constant (kg/div)") is None else val("PR Constant (kg/div)"),
                    "" if val("Soil Type") is None else val("Soil Type"),
                    "" if val("Sample Type") is None else val("Sample Type"),
                    "" if val("Random Seed") is None else val("Random Seed"),
                    "Not generated",
                ]
                rows.append(row)

                if bh_idx is not None and excel_row[bh_idx] is not None:
                    imported_bh = str(excel_row[bh_idx]).strip()
                    if imported_bh:
                        self.bh_id.set(imported_bh)

            wb.close()

            if not rows:
                raise ValueError("No input data rows were found in the Excel file.")

            # Replace current GUI depth rows with imported rows.
            for item in self.tree.get_children():
                self.tree.delete(item)

            self.generated.clear()
            self.selected = None

            for row in rows:
                self.tree.insert("", "end", values=tuple(row))

            self.clear_preview()
            self.status.set(
                f"Imported {len(rows)} depth(s) from Excel."
            )
            messagebox.showinfo(
                "Excel Import Complete",
                f"{len(rows)} depth(s) imported successfully."
            )

        except Exception as exc:
            messagebox.showerror(
                "Excel Import Error",
                str(exc)
            )

